/* ========================================
   HELPERS
======================================== */

/**
 * Display name → full user object
 *
 * Example:
 *
 * getUser("MrArsikk")
 * → users.arsikk0
 */
export const getUser = (displayName) => {

  const nameplate = getNameplate(displayName);

  if (!nameplate) {
    return null;
  }

  return users[nameplate];

};


/**
 * Display name → nameplate
 *
 * Example:
 *
 * getNameplate("MrArsikk")
 * → "arsikk0"
 */
export const getNameplate = (displayName) => {

  for (const [nameplate, user] of Object.entries(users)) {

    if (user.displayNames.includes(displayName)) {
      return nameplate;
    }

  }

  return null;

};


/**
 * Nameplate → full user object
 *
 * Example:
 *
 * getUserByNameplate("arsikk0")
 * → users.arsikk0
 */
export const getUserByNameplate = (nameplate) => {
  return users[nameplate] || null;
};


/**
 * Nameplate → display names
 *
 * Example:
 *
 * getDisplayNames("arsikk0")
 * → ["Arsikk", "MrArsikk"]
 */
export const getDisplayNames = (nameplate) => {
  return users[nameplate]?.displayNames || [];
};


/**
 * Check whether a display name belongs
 * to a particular nameplate.
 *
 * Example:
 *
 * isDisplayName("arsikk0", "MrArsikk")
 * → true
 */
export const isDisplayName = (nameplate, displayName) => {

  return (
    users[nameplate]?.displayNames.includes(displayName) ??
    false
  );

};


/**
 * Get a user's PFP from a display name.
 *
 * Example:
 *
 * getPfp("MrArsikk")
 * → Arsikk's PFP URL
 */
export const getPfp = (displayName) => {

  return getUser(displayName)?.pfp || null;

};


/**
 * Get a user's PFP decoration from a display name.
 */
export const getDecoration = (displayName) => {

  return getUser(displayName)?.decoration || null;

};


/**
 * Get a user's profile bio from a display name.
 */
export const getBio = (displayName) => {

  return getUser(displayName)?.bio || "";

};


/**
 * Get a user's badges from a display name.
 */
export const getBadges = (displayName) => {

  return getUser(displayName)?.badges || [];

};


/**
 * Get a user's friend-page data from a display name.
 */
export const getFriendData = (displayName) => {

  return getUser(displayName)?.friend || null;

};
